  /// Returns the upcoming or current leap for a child of [ageInWeeks].
  static DevelopmentalLeap? nextLeap(int ageInWeeks) {
    try {
      return all.firstWhere((l) => l.leapWeek >= ageInWeeks);
    } catch (_) {
      return null;
    }
  }

  static DevelopmentalLeap? currentLeap(int ageInWeeks) {
    try {
      return all.firstWhere(
        (l) => ageInWeeks >= l.stormyStartWeek && ageInWeeks <= l.leapWeek + 2,
      );
    } catch (_) {
      return null;
    }
  }
